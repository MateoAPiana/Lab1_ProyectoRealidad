    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (!validarCamposSocio()) {
        return; 
        }
        try {
            String dni = txtDni.getText();
            String nombre = txtNombre.getText();
            String apellido = txtApellido.getText();

            int edad = Integer.parseInt(txtEdad.getText());
            String correo = txtCorreo.getText();
            String telefono = txtTelefono.getText();
            boolean estado = true;

            Socio socio = new Socio(dni,  nombre, apellido, edad, correo, telefono, estado);

            socioData.guardarSocio(socio);

            limpiarCampos();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor, ingresa números válidos en DNI y Edad.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        cargarSocios();
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (!validarCamposSocio()) {
        return; // Si algo falla, frena acá
        }
        try {
            int idSocio = Integer.parseInt(txtIdSocio.getText());
            String dni = txtDni.getText();
            String nombre = txtNombre.getText();
            String apellido = txtApellido.getText();
            int edad = Integer.parseInt(txtEdad.getText());
            String correo = txtCorreo.getText();
            String telefono = txtTelefono.getText();

            Socio socio = new Socio();
            socio.setIdSocio(idSocio);
            socio.setDni(dni);
            socio.setNombre(nombre);
            socio.setApellido(apellido);
            socio.setEdad(edad);
            socio.setCorreo(correo);
            socio.setTelefono(telefono);

            socioData.modificarSocio(socio);

            limpiarCampos();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al modificar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        cargarSocios();

    }//GEN-LAST:event_btnModificarActionPerformed

