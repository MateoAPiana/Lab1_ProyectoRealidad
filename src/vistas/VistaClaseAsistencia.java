    public void cargarClases(){
        List<ClaseGym> clases = cd.listarClases(false);
        
        for(ClaseGym c : clases){
            cb_clases.addItem(c.getId() + " - " + c.getDiciplina() + " a las " + c.getHorario());
        }
        
    }
    
    private void armarTabla() {
        tabla.addColumn("ID Asistencia");
        tabla.addColumn("Socio");
        tabla.addColumn("Fecha");
        tabla.addColumn("Entrenador");
        tAsistencias.setModel(tabla);
    }
    
    public void cargarTabla(int id){
        tabla.setRowCount(0);
        List<Asistencia> list = ad.listarAsistenciasPorClase(id);
        for(Asistencia a : list){
            Object[] fila = new Object[]{
                a.getIdAsistencia(),
                a.getSocio().getNombre() + " " + a.getSocio().getApellido(),
                a.getFechaAsistencia(),
                a.getClase().getEntrenador().getNombre() + " " + a.getClase().getEntrenador().getApellido()
            };
            tabla.addRow(fila);
        }
    }

