    public void cargarSocios(){
        List<Socio> socios = sd.listarSocios(false);
        
        for (Socio s : socios){
            cb_socios.addItem(s.getIdSocio() + " - " + s.getNombre() + " " + s.getApellido());
        }
    }
    
    private void armarTabla() {
        tabla.addColumn("ID Pase");
        tabla.addColumn("Cupos");
        tabla.addColumn("Fecha de inicio");
        tabla.addColumn("Fecha de fin");
        tabla.addColumn("Estado");
        tPases.setModel(tabla);
    }

    private void cargarTabla(int id) {
        tabla.setRowCount(0);
        
        List<Pase> lista = pd.listarPasesPorSocio(id);

        for (Pase p : lista) {
            Object[] fila = new Object[]{
                p.getId(),
                p.getCant_entradas(),
                p.getFecha_inicio().toString(),
                p.getFecha_fin().toString(),
                p.isEstado()
            };
            
            tabla.addRow(fila);
        }
    }
    
